// Execute report application logic against an in-memory DOM stub. No browser or network.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const html=fs.readFileSync(path.join(root,'examples/battery-recycling/report.html'),'utf8');
const embedded=html.match(/<script type="application\/json" id="reportData">([\s\S]*?)<\/script>/)[1];
const script=html.match(/<script>\s*('use strict';[\s\S]*?)<\/script>/)[1];
const nodes=new Map();
function node(id){if(!nodes.has(id))nodes.set(id,{value:'',checked:false,hidden:false,textContent:id==='reportData'?embedded:'',innerHTML:'',style:{},dataset:{},appendChild(){},addEventListener(){},querySelectorAll(){return []},classList:{toggle(){}}});return nodes.get(id)}
const context=vm.createContext({document:{getElementById:node,querySelectorAll:()=>[],createElement:()=>({click(){},appendChild(){}}),title:''},URL,Blob,setTimeout:()=>0,console});
vm.runInContext(script,context);
const run=s=>vm.runInContext(s,context);
const baseline=Number(node('nWorks').textContent);
assert.equal(baseline,100);
node('doiOnly').checked=true;run('render()');
assert.equal(Number(node('nWorks').textContent),97);
node('doiOnly').checked=false;
node('year').value='2025';run('render()');
const expected=run('DATA.works.filter(w=>w.year>=2025).length');
assert.equal(Number(node('nWorks').textContent),expected);
node('year').value='';node('query').value='__no_matching_paper__';run('render()');
assert.equal(Number(node('nWorks').textContent),0);
assert.match(node('papers').innerHTML,/No works in this view/);
node('query').value='';run('render()');
const id=run('DATA.works[0].id');
run(`change(${JSON.stringify(id)},'include')`);
assert.equal(Number(node('nSelected').textContent),1);
run(`state.tab='shortlist';render()`);
assert.equal(node('listCount').textContent,'1 shown');
run(`change(${JSON.stringify(id)},'exclude')`);
assert.equal(node('listCount').textContent,'0 shown');
run(`state.author=DATA.authors.find(a=>a.resolved).id;state.tab='papers';render()`);
const authorExpected=run('DATA.works.filter(w=>w.authors.some(a=>a.id===state.author)).length');
assert.equal(Number(node('nWorks').textContent),authorExpected);
assert.equal(run(`esc('<script>')`),'&lt;script&gt;');
assert.equal(run(`cell('=1+1')`),'"\'=1+1"');
assert.equal(run(`url('javascript:alert(1)')`),'#');
run(`download=(name,content,mime)=>{globalThis.lastDownload={name,content,mime}}`);
run(`change(DATA.works[1].id,'include')`);
node('exportCSV').onclick();
assert.match(context.lastDownload.content,/snapshot_sha256/);
assert.match(context.lastDownload.content,new RegExp(run('DATA.snapshot_sha256')));
node('exportDecisions').onclick();
const saved=JSON.parse(context.lastDownload.content);
assert.equal(saved.snapshot_sha256,run('DATA.snapshot_sha256'));
const before=run('JSON.stringify(decisions)');
await node('importDecisions').onchange({target:{files:[{size:100,text:async()=>JSON.stringify({...saved,snapshot_sha256:'different'})}]}});
assert.equal(run('JSON.stringify(decisions)'),before);
await node('importDecisions').onchange({target:{files:[{size:100,text:async()=>JSON.stringify(saved)}]}});
assert.equal(run('JSON.stringify(decisions)'),before);
console.log('PASS: default/DOI/year/text/author filters, shortlist, exclusion, CSV, JSON restore, snapshot isolation, URL/text escaping.');
